import type { ProductRichContent } from "@/lib/product-content/smt-kompleks";

function createInS10Content(cableLength: string, variant: "short" | "long"): ProductRichContent {
  const intro =
    variant === "short"
      ? `Низкочастотный датчик E1 IN-S10 с кабелем ${cableLength} предназначен для удалённого получения данных с ротационных (RVG, RABO) и турбинных (TRZ) счётчиков расхода газа. Короткая комплектация удобна для монтажа в непосредственной близости от корректора или шкафа телеметрии.`
      : `Низкочастотный датчик E1 IN-S10 с кабелем ${cableLength} предназначен для удалённого получения данных с ротационных (RVG, RABO) и турбинных (TRZ) счётчиков расхода газа. Увеличенная длина кабеля позволяет вывести подключение к корректору или шкафу автоматики без наращивания линии на объекте.`;

  return {
    descriptionTitle: "Подробное описание",
    description: [
      { type: "paragraph", text: intro },
      {
        type: "paragraph",
        text: "Считывающее устройство состоит из корпуса, чувствительной платы с тремя независимыми электрическими цепями, а также последовательно соединённых резистора 100 Ом и геркона."
      },
      {
        type: "paragraph",
        text: "Датчик крепится на верхней крышке счётчика так, чтобы при вращении счётных колёс с постоянным магнитом замыкались контакты геркона. Изменение сопротивления передаётся в корректор для расчёта импульсов; частота импульсов соответствует расходу газа."
      },
      {
        type: "paragraph",
        text: "Дополнительный статусный геркон фиксирует воздействие внешнего магнитного поля и используется как сигнал несанкционированного вмешательства в работу счётного прибора."
      }
    ],
    specsTitle: "Основные характеристики",
    specs: [
      {
        characteristic: "Назначение",
        value: "Дистанционная передача данных о расходе газа"
      },
      {
        characteristic: "Совместимость",
        value: "Ротационные счётчики типа RVG, RABO; турбинные счётчики типа TRZ"
      },
      {
        characteristic: "Длина кабеля",
        value: cableLength
      }
    ]
  };
}

export const IN_S10_08M_CONTENT = createInS10Content("0,8 м", "short");
export const IN_S10_25M_CONTENT = createInS10Content("2,5 м", "long");
