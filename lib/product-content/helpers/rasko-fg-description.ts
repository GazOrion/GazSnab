import type { ProductDescriptionBlock } from "@/lib/product-content/smt-kompleks";

type FgFilterRow = {
  slug: string;
  title: string;
  model: string;
  listingParams: string;
  diameter: string;
  filtration: "80 мкм" | "5 мкм";
  hasDpd: boolean;
  dpdNom?: string;
};

function variantIndex(key: string, modulo: number) {
  let hash = 0;
  for (const char of key) {
    hash = (hash + char.charCodeAt(0)) % modulo;
  }
  return hash;
}

const PRINCIPLE_VARIANTS = [
  "Неочищенный газ поступает через входное отверстие, проходит по каналу корпуса и направляется в нижнюю накопительную камеру, где оседают крупные частицы. Далее поток проходит через фильтрующий элемент и выходит в газопровод уже очищенным.",
  "Газовый поток направляется во входной патрубок, затем в корпус фильтра с отбойником и накопительной камерой для крупных включений. После фильтрующего элемента очищенный газ подаётся на выход.",
  "В корпусе фильтра предусмотрен канал с накопительной камерой в нижней части: крупные механические примеси улавливаются до попадания на фильтрующий элемент. Очищенный газ выводится через выходной патрубок."
] as const;

const DPD_VARIANTS = [
  "Контроль загрязнения фильтрующего элемента выполняется индикатором перепада давления ДПД16-, установленным на корпус. Шкала индикатора разделена на зелёную и красную зоны: положение стрелки в красной зоне означает необходимость очистки или замены элемента.",
  "На корпус монтируется индикатор перепада давления типа ДПД16-: одна его сторона соединена с входной, другая — с выходной частью фильтра. При переходе стрелки в красный сектор шкалы фильтрующий элемент считается засорённым и подлежит обслуживанию.",
  "Степень засорения контролируется индикатором ДПД16-, подключённым к входу и выходу фильтра. Красная зона шкалы сигнализирует о необходимости очистки накопительной камеры или замены фильтрующего материала."
] as const;

function buildFiltrationParagraph(row: FgFilterRow): string {
  if (row.filtration === "5 мкм") {
    return `В модели ${row.model} применяется фильтрующий элемент из гофрированного синтетического материала в металлическом армирующем каркасе. Степень фильтрации — не менее 99,5% частиц размером более 0,005 мм (5 мкм).`;
  }

  return `В модели ${row.model} установлен фильтрующий элемент из металлической плетёной сетки в армирующем каркасе из перфорированного металла. Степень фильтрации — не менее 99,5% частиц размером более 0,08 мм (80 мкм).`;
}

function buildIntro(row: FgFilterRow): string {
  const base = `${row.title} (${row.listingParams}) устанавливается на фланцевых участках газопровода диаметром ${row.diameter} для очистки природного газа от механических примесей перед арматурой, приборами учёта и газогорелочными устройствами.`;

  if (row.hasDpd && row.dpdNom) {
    return `${base} Комплектация включает индикатор перепада давления с номинальным ΔP ${row.dpdNom}.`;
  }

  if (row.filtration === "5 мкм") {
    return `${base} Исполнение с повышенной степенью очистки (модификация «В»).`;
  }

  return `${base} Базовое исполнение со стандартной сетчатой фильтрацией.`;
}

export function buildRaskoFgDescriptionBlocks(row: FgFilterRow): ProductDescriptionBlock[] {
  const idx = variantIndex(row.slug, PRINCIPLE_VARIANTS.length);

  const blocks: ProductDescriptionBlock[] = [
    { type: "paragraph", text: buildIntro(row) },
    { type: "heading", text: `Принцип работы ${row.model}`, level: 4 },
    { type: "paragraph", text: PRINCIPLE_VARIANTS[idx] },
    { type: "paragraph", text: buildFiltrationParagraph(row) }
  ];

  if (row.hasDpd) {
    const dpdIdx = variantIndex(`${row.slug}-dpd`, DPD_VARIANTS.length);
    blocks.push({
      type: "paragraph",
      text: `${DPD_VARIANTS[dpdIdx]}${row.dpdNom ? ` Для ${row.model} номинальный перепад ΔPном=${row.dpdNom}.` : ""}`
    });
  }

  blocks.push(
    {
      type: "heading",
      text: `Конструктивные особенности ${row.model}`,
      level: 4
    },
    {
      type: "list",
      items: [
        "Литой корпус из высокопрочного алюминия.",
        "Отбойник и накопительная камера для крупных частиц, защищающие фильтрующий элемент.",
        "Фланцевое присоединение, рабочее давление до 1,6 МПа.",
        "Диапазон температуры рабочей и окружающей среды от −40 до +70 °С.",
        "Замена фильтрующего элемента без демонтажа корпуса из газопровода.",
        "Дополнительные отверстия на корпусе для подключения дифференциального манометра.",
        "Допускается установка во взрывоопасных зонах (разрешение на применение № РРС 00-38692)."
      ]
    }
  );

  return blocks;
}
