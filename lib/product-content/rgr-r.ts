/** Короткий текст для карточки в каталоге (как у СМТ-Комплекс и других категорий). */
export function buildRgrListingDescription(product: RgrProductDefinition): string {
  const qmax = product.extraSpecs.find((row) => row.characteristic === "Максимальный расход Qmax")
    ?.value;
  const du = product.extraSpecs.find((row) => row.characteristic === "Условный диаметр")?.value;

  const params = [qmax, du].filter(Boolean).join(", ");
  if (params) {
    return `Ротационный счётчик газа РГ-Р ${product.typoraзmer}, ${params}. Промышленный учёт природного газа.`;
  }

  return `Ротационный счётчик газа РГ-Р ${product.typoraзmer}. Промышленный учёт природного газа, расход 0,3–1600 м³/ч.`;
}

